"""AegisLake Delta Lake Optimization & Change Data Feed (CDF) Engine.

Implements row-level changelog capture (Delta CDF) for downstream dbt and AI Copilot
consumption, small-file compaction (OPTIMIZE), and multi-dimensional clustering (Z-ORDER).
"""

from pyspark.sql import DataFrame, SparkSession
from delta.tables import DeltaTable


def enable_change_data_feed(spark: SparkSession, table_path: str) -> None:
    """Enables Change Data Feed on a Delta Lake table path.

    Sets the table property 'delta.enableChangeDataFeed = true'.
    This instructs Delta Lake's transaction log (_delta_log) to track row-level
    mutations: insert, update_preimage, update_postimage, and delete.

    Args:
        spark: Active SparkSession.
        table_path: Path to the target Delta Lake directory.
    """
    # [YOUR TURN TO CODE]:
    # Execute the SQL ALTER TABLE command:
    # spark.sql(f"ALTER TABLE delta.`{table_path}` SET TBLPROPERTIES (delta.enableChangeDataFeed = true)")
    spark.sql(f"ALTER TABLE delta.`{table_path}` SET TBLPROPERTIES (delta.enableChangeDataFeed = true)")


def read_silver_change_feed(
    spark: SparkSession,
    table_path: str,
    starting_version: int = 0,
) -> DataFrame:
    """Reads the row-level Change Data Feed from a Delta table starting from a given version.

    The returned DataFrame includes Delta CDF metadata columns:
    - _change_type ('insert', 'update_preimage', 'update_postimage', 'delete')
    - _commit_version (transaction version number)
    - _commit_timestamp (timestamp of commit)

    Args:
        spark: Active SparkSession.
        table_path: Path to the Delta table with CDF enabled.
        starting_version: Delta commit version to start reading changes from (default 0).

    Returns:
        DataFrame: Changelog DataFrame containing mutated records and metadata.
    """
    #  [YOUR TURN TO CODE]:
    # return (
    #     spark.read.format("delta")
    #     .option("readChangeFeed", "true")
    #     .option("startingVersion", starting_version)
    #     .load(table_path)
    # )
    return (
        spark.read.format("delta")
        .option("readChangeFeed", "true")
        .option("startingVersion", starting_version)
        .load(table_path)
    )


def optimize_and_compact_table(
    spark: SparkSession,
    table_path: str,
    zorder_col: str = "authorization_id",
) -> DataFrame:
    """Compacts small files into optimized Parquet blocks and applies Z-Ordering.

    Solves the 'Small File Problem' generated by continuous streaming micro-batches,
    interweaving file statistics to accelerate predicate pushdown and data skipping.

    Args:
        spark: Active SparkSession.
        table_path: Path to the Delta table.
        zorder_col: Column to apply multidimensional Z-Ordering on (default 'authorization_id').

    Returns:
        DataFrame: Optimization execution metrics (numFilesAdded, numFilesRemoved, etc.).
    """
    #  [YOUR TURN TO CODE]:
    # delta_table = DeltaTable.forPath(spark, table_path)
    # return delta_table.optimize().executeZOrderBy(zorder_col)
    delta_table = DeltaTable.forPath(spark, table_path)
    return delta_table.optimize().executeZOrderBy(zorder_col)
